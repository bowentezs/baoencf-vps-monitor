#!/usr/bin/env node
/**
 * 同步 agent 二进制校验和，消除三处真相漂移。
 *
 * 真相来源：frontend/public/download/ 下的二进制文件本身。
 * 产物：
 *   1. frontend/public/download/SHA256SUMS
 *   2. worker/src/generated/agent-shasums.ts（供 /download/SHA256SUMS 路由使用）
 *
 * 两个产物在 .gitattributes 中钉死 eol=lf，校验是逐字节比较，
 * 否则在 core.autocrlf=true 的 Windows 检出上会误报。
 *
 * 用法：
 *   node scripts/sync-agent-sums.mjs           # 重新生成
 *   node scripts/sync-agent-sums.mjs --check   # 只校验，不一致则 exit 1（CI 用）
 */
import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, rename, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const downloadDir = path.join(repoRoot, 'frontend/public/download');
const sumsPath = path.join(downloadDir, 'SHA256SUMS');
const generatedPath = path.join(repoRoot, 'worker/src/generated/agent-shasums.ts');
const checkOnly = process.argv.includes('--check');

function fail(message) {
  console.error(`[agent-sums] ${message}`);
  process.exit(1);
}

async function listBinaryNames() {
  let entries;
  try {
    entries = await readdir(downloadDir, { withFileTypes: true });
  } catch (error) {
    fail(`无法读取 ${downloadDir}（${error?.code || error?.message || error}）`);
  }
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .filter((name) => name !== 'SHA256SUMS' && !name.startsWith('.'))
    .sort();
}

async function collectEntries() {
  const names = await listBinaryNames();
  if (names.length === 0) {
    fail('frontend/public/download 下没有任何二进制，拒绝生成空校验表');
  }
  const entries = [];
  for (const name of names) {
    const bytes = await readFile(path.join(downloadDir, name));
    entries.push(`${createHash('sha256').update(bytes).digest('hex')}  ${name}`);
  }
  return entries;
}

function renderGenerated(entries) {
  return [
    '// AUTO-GENERATED by scripts/sync-agent-sums.mjs. Do not edit by hand.',
    'export const AGENT_SHA256SUMS: readonly string[] = [',
    ...entries.map((line) => `  ${JSON.stringify(line)},`),
    '];',
    '',
  ].join('\n');
}

async function readIfExists(target) {
  try {
    return await readFile(target, 'utf8');
  } catch (error) {
    if (error && error.code === 'ENOENT') return null;
    throw error;
  }
}

async function writeAtomic(target, content) {
  await mkdir(path.dirname(target), { recursive: true });
  const tmp = `${target}.tmp-${process.pid}`;
  await writeFile(tmp, content, 'utf8');
  await rename(tmp, target);
}

const entries = await collectEntries();
const sumsContent = `${entries.join('\n')}\n`;
const generatedContent = renderGenerated(entries);

if (checkOnly) {
  const [currentSums, currentGenerated] = await Promise.all([
    readIfExists(sumsPath),
    readIfExists(generatedPath),
  ]);
  const drifted = [];
  if (currentSums !== sumsContent) drifted.push(sumsPath);
  if (currentGenerated !== generatedContent) drifted.push(generatedPath);
  if (drifted.length > 0) {
    console.error('[agent-sums] 校验和与二进制不一致，请运行 `npm run sync:agent-sums`：');
    for (const file of drifted) console.error(`  - ${path.relative(repoRoot, file)}`);
    process.exit(1);
  }
  console.log(`[agent-sums] OK（${entries.length} 个二进制）`);
  process.exit(0);
}

await writeAtomic(sumsPath, sumsContent);
await writeAtomic(generatedPath, generatedContent);
console.log(`[agent-sums] 已同步 ${entries.length} 个二进制的校验和`);
